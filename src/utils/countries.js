// Helper to find country by name or code
export function findCountry(query) {
  if (!query) return null;
  const q = query.toLowerCase().trim();
  return (
    ALL_COUNTRIES.find(
      (c) =>
        c.name.toLowerCase() === q ||
        c.code === q ||
        c.iso.toLowerCase() === q ||
        c.name.toLowerCase().includes(q)
    ) || null
  );
}
